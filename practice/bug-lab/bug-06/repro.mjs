import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const solution = await import(process.argv[2] ? pathToFileURL(resolve(process.argv[2])).href : './solution.mjs');
const draft = { title: 'Ошибка при входе', description: 'После пароля экран пустой' };
const form = solution.createIssueForm(draft); form.controls.title.markAsDirty();
const result = await solution.submit(form, async () => { throw new Error('503'); });
console.log({ result, draftAfter: form.getRawValue(), enabled: form.enabled });
assert.deepEqual(form.getRawValue(), draft, 'Отказ сервера должен сохранить черновик.');
console.log("Сценарий исправлен. Запустите полную проверку упражнения.");
